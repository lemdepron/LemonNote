/* ---------- AA audit ---------- */

const readTriple = (value) => String(value).trim().split(/\\s+/).map(parseFloat);

export const AA_BODY = 4.5;

function hslToRgb([h, s, l]) {
  const sat = s / 100;
  const lig = l / 100;
  const k = (n) => (n + h / 30) % 12;
  const a = sat * Math.min(lig, 1 - lig);
  const f = (n) => lig - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1));
  return [f(0), f(8), f(4)];
}

const linear = (v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);

function luminance([h, s, l]) {
  const [r, g, b] = hslToRgb([h, s, l]).map(linear);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrastOf(a, b) {
  const la = luminance(a);
  const lb = luminance(b);
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
}

export function presetContrast(preset) {
  const report = {};
  ["light", "dark"].forEach((mode) => {
    const tokens = preset?.tokens?.[mode];
    if (!tokens || !tokens["--background"] || !tokens["--foreground"]) return;
    const bg = readTriple(tokens["--background"]);
    const ratio = (name) =>
      tokens[name] ? Number(contrastOf(readTriple(tokens[name]), bg).toFixed(2)) : null;
    report[mode] = {
      body: ratio("--foreground"),
      soft: ratio("--muted-foreground"),
      button: tokens["--primary"] && tokens["--primary-foreground"]
        ? Number(contrastOf(readTriple(tokens["--primary-foreground"]), readTriple(tokens["--primary"])).toFixed(2))
        : null,
      link: ratio("--link"),
    };
  });
  return report;
}

export function auditContrast(min = AA_BODY) {
  const failures = [];
  THEME_PRESETS.forEach((preset) => {
    const report = presetContrast(preset);
    Object.entries(report).forEach(([mode, values]) => {
      Object.entries(values).forEach(([key, ratio]) => {
        if (ratio != null && ratio < min) failures.push({ theme: preset.name, mode, key, ratio });
      });
    });
  });
  return failures;
}

export function auditDistinctiveness(minDist = 12) {
  const failures = [];
  const themes = THEME_PRESETS.filter(p => p.id !== "notecraft");
  
  function colorDistance(hsl1, hsl2) {
    const [h1, s1, l1] = hsl1;
    const [h2, s2, l2] = hsl2;
    const dh = Math.min(Math.abs(h1 - h2), 360 - Math.abs(h1 - h2));
    return Math.sqrt(dh*dh + (s1-s2)*(s1-s2) + (l1-l2)*(l1-l2));
  }

  for (let i = 0; i < themes.length; i++) {
    for (let j = i + 1; j < themes.length; j++) {
      const t1 = themes[i];
      const t2 = themes[j];
      ["light", "dark"].forEach(mode => {
        const tokens1 = t1.tokens?.[mode];
        const tokens2 = t2.tokens?.[mode];
        if (!tokens1 || !tokens2) return;
        const d1 = colorDistance(readTriple(tokens1["--primary"]), readTriple(tokens2["--primary"]));
        const d2 = colorDistance(readTriple(tokens1["--background"]), readTriple(tokens2["--background"]));
        const avgDist = (d1 + d2) / 2;
        if (avgDist < minDist) {
          failures.push({
            theme1: t1.name,
            theme2: t2.name,
            mode,
            distance: Number(avgDist.toFixed(2)),
            minDist
          });
        }
      });
    }
  }
  return failures;
}

