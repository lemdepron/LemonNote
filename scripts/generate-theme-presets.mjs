function buildModeTokens(modeTokens) {
  const lines = [];
  for (const [key, value] of Object.entries(modeTokens)) {
    if (key === "--bg-pattern") {
      // bg-pattern is handled in style layer
      continue;
    }
    lines.push(`      "${key}": "${value}",`);
  }
  return lines.join("\n");
}

function buildTheme(theme, familyConfig, mode) {
  const styleLayer = buildStyleLayer(familyConfig, mode, familyConfig.shadowStyle);
  const modeTokens = theme[mode];
  const styleConfig = STYLE_TOKENS[familyConfig.name][mode];

  // Filter out style tokens from mode tokens to avoid duplication
  const styleKeys = new Set([
    "--r-control", "--r-card", "--r-pill", "--r-tab",
    "--border-width", "--shadow-style", "--shadow-card", "--shadow-pop",
    "--blur", "--surface-opacity", "--font-heading", "--font-body",
    "--tab-style", "--button-style", "--bg-gradient", "--bg-gradient-dark", "--bg-pattern"
  ]);

  const filteredTokens = {};
  for (const [k, v] of Object.entries(modeTokens)) {
    if (!styleKeys.has(k)) {
      filteredTokens[k] = v;
    }
  }

  return `    ${mode}: {
${buildModeTokens(filteredTokens)}
${buildStyleLayer(STYLE_TOKENS[familyConfig.name], mode, STYLE_TOKENS[familyConfig.name].shadowStyle)}
    }`;
}

