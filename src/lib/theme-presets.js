/* ---------- 36 FINAL THEMES (18 light + 18 dark) ---------- */
/* Each theme is a dual-mode preset with explicit hand-chosen tokens.
 * Structure: { id, name, surface, light: {...tokens...}, dark: {...tokens...} }
 * Tokens are full HSL strings like "42 32% 96%".
 * The generator functions below are kept for reference but not used for these 36.
 */

function buildFinalPreset(spec) {
  return {
    id: spec.id,
    name: spec.name,
    mode: null, // dual-mode
    surface: spec.surface,
    tokens: {
      light: spec.light,
      dark: spec.dark,
    },
  };
}

